fn tool_profile(tool: &str) -> Option<&'static ToolProfile> {
    TOOL_PROFILES.iter().find(|profile| profile.id == tool)
}

pub(crate) fn tool_model_sync_policy(tool: &str) -> ToolModelSyncPolicy {
    tool_profile(tool)
        .map(|profile| profile.model_sync_policy)
        .unwrap_or(ToolModelSyncPolicy::None)
}

fn tool_runtime_display_name(tool: &str) -> &str {
    tool_profile(tool)
        .map(|profile| profile.display_name)
        .unwrap_or(tool)
}

fn tool_runtime_kill_manifest(tool: &str) -> Option<ToolRuntimeKillManifest> {
    tool_profile(tool).map(|profile| profile.runtime)
}

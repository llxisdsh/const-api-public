#[derive(Clone, Copy, Debug)]
struct ToolRuntimeKillManifest {
    commands: &'static [&'static str],
    windows_process_names: &'static [&'static str],
    macos_process_names: &'static [&'static str],
    linux_process_names: &'static [&'static str],
    extension_dir_prefixes: &'static [&'static str],
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ToolCommandLaunch {
    Disabled,
    Terminal,
    Desktop,
}

#[derive(Clone, Copy, Debug)]
struct ToolProfile {
    id: &'static str,
    display_name: &'static str,
    protocols: &'static [ToolProtocol],
    default_protocol: ToolProtocol,
    model_sync_policy: ToolModelSyncPolicy,
    runtime: ToolRuntimeKillManifest,
    command_launch: ToolCommandLaunch,
    launch_args: &'static [&'static str],
    desktop_preferred: bool,
    identity_aliases: &'static [&'static str],
    external_environment_names: &'static [&'static str],
    #[cfg_attr(not(target_os = "macos"), allow(dead_code))]
    macos_app_names: &'static [&'static str],
    #[cfg_attr(not(target_os = "windows"), allow(dead_code))]
    windows_program_paths: &'static [(&'static str, &'static str)],
}

const fn runtime_command_manifest(commands: &'static [&'static str]) -> ToolRuntimeKillManifest {
    ToolRuntimeKillManifest {
        commands,
        windows_process_names: &[],
        macos_process_names: &[],
        linux_process_names: &[],
        extension_dir_prefixes: &[],
    }
}

const fn desktop_and_command_manifest(
    commands: &'static [&'static str],
    windows_process_names: &'static [&'static str],
    macos_process_names: &'static [&'static str],
    linux_process_names: &'static [&'static str],
) -> ToolRuntimeKillManifest {
    ToolRuntimeKillManifest {
        commands,
        windows_process_names,
        macos_process_names,
        linux_process_names,
        extension_dir_prefixes: &[],
    }
}

